def sharp_drop_cutoff(values: list[float]) -> int:
    if len(values) < 3:
        return len(values)
    diffs = [right - left for left, right in zip(values, values[1:])]
    median_abs = statistics.median(abs(value) for value in diffs)
    threshold = max(0.5, 8.0 * median_abs)
    for idx, diff in enumerate(diffs):
        if diff < -threshold:
            return max(2, idx + 1)
    return len(values)


def forecast_rollouts(experiment_root: Path) -> None:
    artifact_root = experiment_root / "docs" / "empirical-2" / "artifacts"
    files = {
        "Sequential": "forecasting-longhorizon-patchtst-3task-tasknorm-fit-sequential-seed0.json",
        "EF-EWC": "forecasting-longhorizon-patchtst-3task-tasknorm-fit-ef-seed0-lam729.json",
        "U-IEWC": "forecasting-longhorizon-patchtst-3task-tasknorm-fit-iewc-seed0-lam9.json",
        "GSS-IEWC": "forecasting-longhorizon-patchtst-3task-tasknorm-fit-iewc_gss-seed0-lam9.json",
    }
    data = {method: load_json(artifact_root / name) for method, name in files.items()}
    reference = data["GSS-IEWC"]["rollouts"]
    frequencies = [name for name in ("Weather", "ECL", "Traffic") if name in reference]
    lines = [
        "\\begin{tikzpicture}",
        "\\begin{groupplot}[group style={group size=1 by 3,vertical sep=8mm},iewc axis,width=\\columnwidth,height=.25\\columnwidth,xmin=-122]",
    ]
    for panel, frequency in enumerate(frequencies):
        candidates = []
        for idx, rollout in enumerate(reference[frequency]):
            cutoff = sharp_drop_cutoff([float(v) for v in rollout["target"]])
            candidates.append((cutoff, -idx, idx))
        cutoff, _, rollout_index = max(candidates)
        ref = reference[frequency][rollout_index]
        context_values = [float(v) for v in ref["context"]]
        context_tail = min(120, len(context_values))
        context_values = context_values[-context_tail:]
        target_values = [float(v) for v in ref["target"][:cutoff]]
        xmax = max(22, len(target_values) + 2)
        legend = ",legend to name=forecastlegend,legend columns=3" if panel == 0 else ""
        ylabel = "Normalized value" if panel == 1 else ""
        xlabel = "Forecast step" if panel == 2 else ""
        lines.append(
            f"\\nextgroupplot[title={{\\textbf{{{chr(65+panel)}}}\\quad {frequency}}},ylabel={{{ylabel}}},xlabel={{{xlabel}}},xmax={xmax}{legend}]"
        )
        context_coords = " ".join(
            f"({x},{f(y)})"
            for x, y in zip(range(-context_tail, 0), context_values)
        )
        target_coords = " ".join(
            f"({x},{f(y)})" for x, y in enumerate(target_values)
        )
        lines.append(f"\\addplot+[context] coordinates {{{context_coords}}};")
        if panel == 0:
            lines.append("\\addlegendentry{Context}")
        lines.append(f"\\addplot+[target] coordinates {{{target_coords}}};")
        if panel == 0:
            lines.append("\\addlegendentry{Target}")
        for method, style in (
            ("Sequential", "sequential"),
            ("EF-EWC", "ewc"),
            ("U-IEWC", "iewc"),
            ("GSS-IEWC", "iewcrdw"),
        ):
            pred = [
                float(v)
                for v in data[method]["rollouts"][frequency][rollout_index]["prediction"][:cutoff]
            ]
            coords = " ".join(f"({x},{f(y)})" for x, y in enumerate(pred))
            lines.append(f"\\addplot+[{style},mark=none] coordinates {{{coords}}};")
            if panel == 0:
                lines.append(f"\\addlegendentry{{{METHOD_LABELS[method]}}}")
        lines.append(
            f"\\addplot[IEWCLight,line width=.45pt,forget plot] coordinates {{(-.5,{f(min(target_values + context_values))})(-.5,{f(max(target_values + context_values))})}};"
        )
    lines.extend(
        [
            "\\end{groupplot}",
            "\\node[anchor=south] at ($(group c1r1.north west)!0.5!(group c1r1.north east)+(0,9mm)$) {\\pgfplotslegendfromname{forecastlegend}};",
            "\\end{tikzpicture}",
        ]
    )
    write("forecast_rollouts_longhorizon_tasknorm_selected.tex", "\n".join(lines))


def selected_baseline(selected: dict, domain: str) -> float:
    payload = selected["domains"][domain]
    chosen = float(payload["selected_lambdas"]["ief_uniform"])
    matches = [
        item
        for item in payload["grid_summaries"]
        if item["method"] == "ief_uniform"
        and math.isclose(float(item["lambda"]), chosen, rel_tol=0.0, abs_tol=1e-15)
    ]
    if len(matches) != 1:
        raise RuntimeError(f"Expected one selected IEF baseline for {domain}")
    return float(matches[0]["metric_values"][0])


def damping_sensitivity(experiment_root: Path, internal_root: Path) -> None:
    historical = load_json(
        experiment_root
        / "docs"
        / "empirical-evidence"
        / "artifacts"
        / "facil-prefix3-iewc-diag-tau-sensitivity.json"
    )["rows"]
    historical = [row for row in historical if row.get("status") == "ok"]
    historical.sort(key=lambda row: float(row["tau"]))
    default = next(row for row in historical if math.isclose(float(row["tau"]), 0.01))
    acc_delta = [float(row["final_avg_taw"]) - float(default["final_avg_taw"]) for row in historical]
    retention_delta = [float(default["avg_forgetting_taw"]) - float(row["avg_forgetting_taw"]) for row in historical]

    artifacts = internal_root / "artifacts"
    selected = load_json(artifacts / "selected-lambdas.json")
    sensitivity_root = artifacts / "confirmatory-sensitivities" / "validation"
    domain_points = {}
    for domain in ("imagenet_r", "trace"):
        baseline = selected_baseline(selected, domain)
        points = {0.01: 0.0}
        for path in (sensitivity_root / domain).glob("*relative_damping*.json"):
            payload = load_json(path)
            value = float(payload["sensitivity"]["value"])
            metric = float(payload.get("final_avg_accuracy", payload.get("final_avg_score")))
            points[value] = metric - baseline
        domain_points[domain] = points

    tau_labels = [
        "$10^{-6}$",
        "$10^{-5}$",
        "$10^{-4}$",
        "$10^{-3}$",
        "$10^{-2}$",
        "$3\\cdot10^{-2}$",
        "$10^{-1}$",
    ]
    kappa_values = [0.0, 0.001, 0.01, 0.1, 1.0]
    kappa_labels = ["$0$", "$10^{-3}$", "$10^{-2}$", "$10^{-1}$", "$1$"]
    lines = [
        "\\begin{tikzpicture}",
        "\\begin{groupplot}[group style={group size=2 by 1,horizontal sep=10mm},iewc axis,width=.47\\linewidth,height=.28\\linewidth,ymin=-.032,ymax=.032]",
        "\\nextgroupplot[title={\\textbf{A}\\quad Fixed $\\tau$ (CIFAR-100)},xlabel={Fixed damping, $\\tau$},ylabel={$\\Delta$ metric vs. $10^{-2}$},xmin=-.2,xmax=6.2,xtick={0,1,2,3,4,5,6},xticklabels={"
        + ",".join(tau_labels)
        + "},legend to name=dampingleftlegend,legend columns=2]",
        "\\addplot[IEWCMid,line width=.45pt,forget plot] coordinates {(0,0)(6,0)};",
        "\\addplot+[accuracy] coordinates {"
        + " ".join(f"({idx},{f(value)})" for idx, value in enumerate(acc_delta))
        + "};",
        "\\addlegendentry{Accuracy}",
        "\\addplot+[retention] coordinates {"
        + " ".join(f"({idx},{f(value)})" for idx, value in enumerate(retention_delta))
        + "};",
        "\\addlegendentry{$-$forgetting}",
        "\\nextgroupplot[title={\\textbf{B}\\quad Relative $\\kappa$ (validation)},xlabel={Relative damping, $\\kappa$},ylabel={$\\Delta$ validation score},xmin=-.2,xmax=4.2,xtick={0,1,2,3,4},xticklabels={"
        + ",".join(kappa_labels)
        + "},legend to name=dampingrightlegend,legend columns=2]",
        "\\addplot[IEWCMid,line width=.45pt,forget plot] coordinates {(0,0)(4,0)};",
    ]
    for domain, style, label in (
        ("imagenet_r", "domainone", "ImageNet-R"),
        ("trace", "domaintwo", "TRACE"),
    ):
        coords = " ".join(
            f"({idx},{f(domain_points[domain][value])})"
            for idx, value in enumerate(kappa_values)
        )
        lines.append(f"\\addplot+[{style}] coordinates {{{coords}}};")
        lines.append(f"\\addlegendentry{{{label}}}")
    lines.extend(
        [
            "\\end{groupplot}",
            "\\node[anchor=south] at ($(group c1r1.north west)!0.5!(group c1r1.north east)+(0,7mm)$) {\\pgfplotslegendfromname{dampingleftlegend}};",
            "\\node[anchor=south] at ($(group c2r1.north west)!0.5!(group c2r1.north east)+(0,7mm)$) {\\pgfplotslegendfromname{dampingrightlegend}};",
            "\\end{tikzpicture}",
        ]
    )
    write("damping_sensitivity.tex", "\n".join(lines))


def empirical_module(experiment_root: Path):
    path = experiment_root / "scripts" / "build_empirical_artifacts.py"
    spec = importlib.util.spec_from_file_location("iewc_empirical_artifacts", path)
    if spec is None or spec.loader is None:
        raise RuntimeError(f"Cannot load {path}")
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def ecdf_points(values: list[float], maximum: int = 320) -> list[tuple[float, float]]:
    values = sorted(value for value in values if value > 0 and math.isfinite(value))
    step = max(1, len(values) // maximum)
    points = [(values[idx], (idx + 1) / len(values)) for idx in range(0, len(values), step)]
    if points[-1][0] != values[-1]:
        points.append((values[-1], 1.0))
    return points


def summand_ecdf(experiment_root: Path) -> None:
    module = empirical_module(experiment_root)
    records = (
        module.collect_facil_summand_norms()
        + module.collect_synthetic_summand_norms()
        + module.collect_segmentation_summand_norms()
    )
    tasks = ("Classification", "Regression", "Diffusion", "Segmentation")
    lines = [
        "\\begin{tikzpicture}",
        "\\begin{groupplot}[group style={group size=4 by 1,horizontal sep=2mm},iewc axis,width=.245\\linewidth,height=.245\\linewidth,xmode=log,ymin=0,ymax=1.02]",
    ]
    for idx, task in enumerate(tasks):
        ylabel = "Empirical CDF" if idx == 0 else ""
        ylabels = "" if idx == 0 else ",yticklabels={\\empty}"
        legend = ",legend to name=summandlegend,legend columns=2" if idx == 0 else ""
        lines.append(
            f"\\nextgroupplot[title={{\\textbf{{{chr(65+idx)}}}\\quad {task}}},ylabel={{{ylabel}}}{ylabels}{legend}]"
        )
        for method, style, label in (
            ("EF-EWC", "ewc", "EWC"),
            ("IEWC", "iewc", "IEWC"),
        ):
            values = [
                float(item["effective_trace"])
                for item in records
                if item["task"] == task and item["method"] == method
            ]
            coords = " ".join(f"({f(x)},{f(y)})" for x, y in ecdf_points(values))
            lines.append(f"\\addplot+[{style},mark=none] coordinates {{{coords}}};")
            if idx == 0:
                lines.append(f"\\addlegendentry{{{label}}}")
    lines.extend(
        [
            "\\end{groupplot}",
            "\\node[anchor=north,font=\\scriptsize] at ($(group c1r1.south west)!0.5!(group c4r1.south east)+(0,-6mm)$) {Effective diagonal summand trace ($\\lambda\\times$ trace)};",
            "\\node[anchor=south] at ($(group c1r1.north west)!0.5!(group c4r1.north east)+(0,7mm)$) {\\pgfplotslegendfromname{summandlegend}};",
            "\\end{tikzpicture}",
        ]
    )
    write("summand_norm_ecdf.tex", "\n".join(lines))


def contamination_spectra(experiment_root: Path) -> None:
    module = empirical_module(experiment_root)
    records = module.collect_spectra()
    grouped: dict[tuple[str, float], list[list[float]]] = defaultdict(list)
    for record in records:
        method = record["method"]
        noise = float(record["noise"])
        if method in {"EF-EWC", "IEWC"} and noise in {0.0, 0.1, 0.25}:
            grouped[(method, noise)].append([float(value) for value in record["values"]])
    styles = {
        ("EF-EWC", 0.0): "color=IEWCDark,solid",
        ("EF-EWC", 0.1): "color=IEWCDark,dashed",
        ("EF-EWC", 0.25): "color=IEWCDark,dotted",
        ("IEWC", 0.0): "color=IEWCPrimary,solid,line width=1pt",
        ("IEWC", 0.1): "color=IEWCPrimary,dashed,line width=1pt",
        ("IEWC", 0.25): "color=IEWCPrimary,dotted,line width=1pt",
    }
    lines = [
        "\\begin{tikzpicture}",
        "\\begin{axis}[iewc axis,width=.92\\linewidth,height=.36\\linewidth,ymode=log,xlabel={Sorted diagonal-entry rank},ylabel={Mean top diagonal entry},legend columns=3,legend style={at={(.5,1.03)},anchor=south}]",
    ]
    for method in ("EF-EWC", "IEWC"):
        for noise in (0.0, 0.1, 0.25):
            arrays = grouped[(method, noise)]
            length = min(len(array) for array in arrays)
            means = [statistics.mean(array[idx] for array in arrays) for idx in range(length)]
            coords = " ".join(f"({idx+1},{f(value)})" for idx, value in enumerate(means))
            label = "EWC (OPG)" if method == "EF-EWC" else "IEWC"
            lines.append(f"\\addplot[{styles[(method, noise)]},mark=none] coordinates {{{coords}}};")
            lines.append(f"\\addlegendentry{{{label}, $p={noise:g}$}}")
    lines.extend(["\\end{axis}", "\\end{tikzpicture}"])
    write("contamination_diagonal_spectra.tex", "\n".join(lines))


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--experiment-root",
        type=Path,
        default=ROOT.parent / "iewc",
        help="IEWC experiment repository containing retained records",
    )
    parser.add_argument(
        "--internal-root",
        type=Path,
        default=ROOT.parent / "iewc-paper-internal" / "resubmission-1",
        help="Revision task arc containing confirmatory sensitivity records",
    )
    args = parser.parse_args()
    classification_retention(args.experiment_root)
    nlp_retention(args.experiment_root)
    forecast_rollouts(args.experiment_root)
    damping_sensitivity(args.experiment_root, args.internal_root)
    summand_ecdf(args.experiment_root)
    contamination_spectra(args.experiment_root)
    print(f"wrote TikZ sources to {OUT}")


if __name__ == "__main__":
    main()
