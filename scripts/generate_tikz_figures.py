def f(value: float) -> str:
    if abs(value) < 5e-13:
        return "0"
    return f"{value:.8g}"


def write(name: str, body: str) -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / name).write_text(
        "% Generated by scripts/generate_tikz_figures.py; edit source data or generator.\n"
        + body.rstrip()
        + "\n"
    )


def load_json(path: Path) -> dict:
    return json.loads(path.read_text())


def mean_sd(rows: list[list[float]]) -> tuple[list[float], list[float]]:
    columns = list(zip(*rows))
    means = [statistics.mean(column) for column in columns]
    sds = [statistics.stdev(column) if len(column) > 1 else 0.0 for column in columns]
    return means, sds


def retention_summary(
    artifact_root: Path, files: list[str], matrix_key: str
) -> tuple[list[float], list[float], list[float], list[float]]:
    matrices = [load_json(artifact_root / name)[matrix_key] for name in files]
    final_rows = [[float(v) for v in matrix[-1]] for matrix in matrices]
    forgetting_rows = []
    for matrix, final in zip(matrices, final_rows):
        best = [max(float(row[col]) for row in matrix) for col in range(len(final))]
        forgetting_rows.append([best[col] - final[col] for col in range(len(final))])
    final_mean, final_sd = mean_sd(final_rows)
    forgetting_mean, forgetting_sd = mean_sd(forgetting_rows)
    return final_mean, final_sd, forgetting_mean, forgetting_sd


def band_and_curve(
    xs: list[float], means: list[float], sds: list[float], style: str, color: str
) -> str:
    upper = " ".join(
        f"({f(x)},{f(mean + sd)})" for x, mean, sd in zip(xs, means, sds)
    )
    lower = " ".join(
        f"({f(x)},{f(mean - sd)})"
        for x, mean, sd in reversed(list(zip(xs, means, sds)))
    )
    curve = " ".join(f"({f(x)},{f(y)})" for x, y in zip(xs, means))
    return (
        f"\\addplot[draw=none,fill={color},fill opacity=.08,forget plot] "
        f"coordinates {{{upper} {lower}}} -- cycle;\n"
        f"\\addplot+[{style}] coordinates {{{curve}}};"
    )


def retention_figure(
    *,
    artifact_root: Path,
    methods: dict[str, list[str]],
    matrix_key: str,
    task_labels: list[str],
    output_name: str,
    left_ylabel: str,
    panel_labels: tuple[str, str] = ("A", "B"),
    show_legend: bool = True,
) -> None:
    summaries = {
        method: retention_summary(artifact_root, files, matrix_key)
        for method, files in methods.items()
    }
    xs = list(range(1, len(task_labels) + 1))
    colors = {
        "sequential": "IEWCLight",
        "ewc": "IEWCDark",
        "ewcdr": "IEWCMid",
        "iewc": "IEWCPrimary",
        "iewcrdw": "IEWCSecondary",
    }
    if len(task_labels) == 10:
        xticklabels = ",".join(task_labels)
        xopts = f"xmin=.7,xmax=10.3,xtick={{{','.join(map(str, xs))}}},xticklabels={{{xticklabels}}}"
        height = ".34"
    else:
        compact = ["C-STANCE", "FOMC", "SciQA"]
        xopts = (
            f"xmin=.8,xmax={len(xs)+.2},xtick={{{','.join(map(str, xs))}}},"
            f"xticklabels={{{','.join(compact)}}},"
            "xticklabel style={font=\\tiny,rotate=18,anchor=north east}"
        )
        height = ".37"
    legend_option = (
        f",legend to name={output_name}legend,legend columns=3"
        if show_legend
        else ""
    )
    lines = [
        "\\begin{tikzpicture}",
        "\\begin{groupplot}[group style={group size=2 by 1,horizontal sep=11mm},",
        f"iewc axis,width=.425\\columnwidth,height={height}\\columnwidth,{xopts}]",
        f"\\nextgroupplot[title={{\\textbf{{{panel_labels[0]}}}\\quad Performance}},ylabel={{{left_ylabel}}}{legend_option}]",
    ]
    for method in methods:
        final_mean, final_sd, _, _ = summaries[method]
        style = METHODS[method]
        lines.append(band_and_curve(xs, final_mean, final_sd, style, colors[style]))
        if show_legend:
            lines.append(f"\\addlegendentry{{{METHOD_LABELS[method]}}}")
    lines.append(
        f"\\nextgroupplot[title={{\\textbf{{{panel_labels[1]}}}\\quad Forgetting}}]"
    )
    for method in methods:
        _, _, forget_mean, forget_sd = summaries[method]
        style = METHODS[method]
        lines.append(band_and_curve(xs, forget_mean, forget_sd, style, colors[style]))
    lines.append("\\end{groupplot}")
    if show_legend:
        lines.append(
            f"\\node[anchor=south] at ($(group c1r1.north west)!0.5!(group c2r1.north east)+(0,9mm)$) {{\\pgfplotslegendfromname{{{output_name}legend}}}};"
        )
    lines.append("\\end{tikzpicture}")
    write(f"{output_name}.tex", "\n".join(lines))


